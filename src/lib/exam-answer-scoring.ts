/** Exam-primary-score contracts, NOT XP rules. No mutation of learning state.
 * A reviewed draft is never an approved final specification. Unknown rules fail closed.
 */
export type ExamAnswerContract = {
  id: string;
  year: number;
  documentStatus: "draft-copy-reviewed" | "local-draft-reviewed";
  mode: "exact-numeric" | "exact-ordered" | "exact-unordered" | "ordered-one-error" | "two-cell-pair" | "selection-one-error" | "sequence-two-errors-extra-penalty";
  maximum: 1 | 2;
  partialCredit: boolean;
  source: { url: string; pdfPage: number; section: string };
  limitations: string[];
};
const chem = "https://pro-schools.ru/fipi/ege/spec/2027/hi-11-ege-2027-spec.pdf";
const bio = "https://pro-schools.ru/fipi/ege/spec/2027/bi-11-ege-2027-spec.pdf";
const info = "https://pro-schools.ru/fipi/ege/spec/2027/inf-11-ege-2027-spec.pdf";
const contract = (id: string, mode: ExamAnswerContract["mode"], maximum: 1 | 2, url: string, pdfPage: number): ExamAnswerContract => ({
  id, year: 2027, documentStatus: "draft-copy-reviewed", mode, maximum,
  partialCredit: maximum === 2, source: { url, pdfPage, section: "10. Система оценивания" },
  limitations: ["Проект 2027 по PDF-копии, не окончательная утверждённая версия", "Формат ключа и допустимые варианты должны быть проверены для конкретного подтипа"],
});
export function getExamAnswerContract(modelId: string, number: number): ExamAnswerContract | null {
  if (modelId === "ege-chemistry") {
    if ([6, 7, 8, 14, 15, 22, 23, 24].includes(number)) return contract(`${modelId}-${number}`, "ordered-one-error", 2, chem, 6);
    if ([26, 27, 28].includes(number)) return contract(`${modelId}-${number}`, "exact-numeric", 1, chem, 6);
    if ([1, 3, 4, 11, 12, 13, 18].includes(number)) return contract(`${modelId}-${number}`, "exact-unordered", 1, chem, 6);
    if (number >= 1 && number <= 28) return contract(`${modelId}-${number}`, "exact-ordered", 1, chem, 6);
  }
  if (modelId === "ege-biology") {
    if ([3, 4].includes(number)) return contract(`${modelId}-${number}`, "exact-numeric", 1, bio, 7);
    if ([1, 5, 9, 13, 21].includes(number)) return contract(`${modelId}-${number}`, "exact-ordered", 1, bio, 7);
    if ([2, 6, 10, 14, 19, 20].includes(number)) return contract(`${modelId}-${number}`, "ordered-one-error", 2, bio, 7);
    if ([7, 11, 15, 17, 18].includes(number)) return contract(`${modelId}-${number}`, "selection-one-error", 2, bio, 7);
    if ([8, 12, 16].includes(number)) return {
      ...contract(`${modelId}-${number}`, "sequence-two-errors-extra-penalty", 2, bio, 7),
      limitations: ["Проект 2027: до двух неверных позиций — 1 балл; превышение длины снижает оценку на 1", "Неполная последовательность направляется на проверку: трактовка пропущенных позиций отдельно не подтверждена"],
    };
  }
  if (modelId === "ege-informatics") {
    if ([26, 27].includes(number)) return contract(`${modelId}-${number}`, "two-cell-pair", 2, info, 7);
    if (number >= 1 && number <= 25) return contract(`${modelId}-${number}`, "exact-ordered", 1, info, 6);
  }
  return null;
}

/** Explicit cells prevent guessing where one multi-digit number ends and another starts.
 * Empty cells are represented by "". Extra cells are invalid, not silently truncated.
 * Alternatives must come from the reviewed item, never generated by this scorer.
 */
export function scoreExamAnswer(
  rule: ExamAnswerContract,
  key: readonly string[],
  response: readonly string[],
  alternatives: readonly (readonly string[])[] = [],
): { points: number | null; maximum: number; kind: "draft-primary-score" | "manual-review-required" } {
  const clean = (cells: readonly string[]) => cells.map(s => s.trim());
  const expected = clean(key), actual = clean(response);
  if (!expected.length || expected.some(s => !s)) throw new Error("A non-empty reviewed key is required");
  if (rule.mode === "two-cell-pair" && expected.length !== 2) throw new Error("Two-cell key required");
  if (rule.mode === "exact-numeric" && expected.length !== 1) throw new Error("Single numeric key required");
  const validNumeric = (s: string) => /^[-+]?\d+(?:[.,]\d+)?$/.test(s);
  if (rule.mode === "exact-numeric" && !validNumeric(expected[0])) throw new Error("Official numeric key must be integer or terminating decimal");
  const same = (a: readonly string[], b: readonly string[]) => a.length === b.length && a.every((s, i) => s === b[i]);
  const evaluate = (reference: string[]) => {
    if (rule.mode === "selection-one-error") {
      const count = (xs: string[]) => xs.reduce<Map<string, number>>((m, s) => m.set(s, (m.get(s) ?? 0) + 1), new Map());
      const expectedCounts = count(reference), actualCounts = count(actual);
      const symbols = new Set([...reference, ...actual]);
      let missing = 0, extra = 0;
      for (const symbol of symbols) {
        const delta = (expectedCounts.get(symbol) ?? 0) - (actualCounts.get(symbol) ?? 0);
        missing += Math.max(delta, 0); extra += Math.max(-delta, 0);
      }
      if (!missing && !extra) return 2;
      return actual.every(Boolean) && Math.max(missing, extra) === 1 ? 1 : 0;
    }
    if (rule.mode === "sequence-two-errors-extra-penalty") {
      if (actual.length < reference.length || !actual.every(Boolean)) return null;
      const errors = reference.filter((s, i) => s !== actual[i]).length;
      return Math.max(0, (errors === 0 ? 2 : errors <= 2 ? 1 : 0) - (actual.length > reference.length ? 1 : 0));
    }
    if (actual.length > reference.length) return 0;
    if (rule.mode === "exact-numeric") return actual.length === 1 && validNumeric(actual[0]) && checkTaskAnswer(actual[0], { type: "number", value: reference[0] }).correct ? 1 : 0;
    if (rule.mode === "exact-unordered") return same([...reference].sort(), [...actual].sort()) ? 1 : 0;
    if (same(reference, actual)) return rule.maximum;
    if (rule.mode === "ordered-one-error") return actual.length === reference.length && actual.every(Boolean) && reference.filter((s, i) => s !== actual[i]).length === 1 ? 1 : 0;
    if (rule.mode === "two-cell-pair") {
      const equal = (a: string | undefined, b: string) => Boolean(a && validNumeric(a) && validNumeric(b) && checkTaskAnswer(a, { type: "number", value: b }).correct);
      if (actual.length === 2 && reference.every((s, i) => equal(actual[i], s))) return 2;
      return reference.some((s, i) => equal(actual[i], s)) || (actual.length === 2 && equal(actual[0], reference[1]) && equal(actual[1], reference[0])) ? 1 : 0;
    }
    return 0;
  };
  for (const alternate of alternatives) {
    if (alternate.length !== expected.length || alternate.some(s => !s.trim())) throw new Error("Alternative key shape differs from reviewed key");
    if (rule.mode === "exact-numeric" && !validNumeric(alternate[0].trim())) throw new Error("Invalid alternative numeric key");
  }
  const results = [expected, ...alternatives.map(clean)].map(evaluate);
  if (results.some(n => n === rule.maximum)) return { points: rule.maximum, maximum: rule.maximum, kind: "draft-primary-score" };
  if (results.some(n => n === null)) return { points: null, maximum: rule.maximum, kind: "manual-review-required" };
  return { points: Math.max(...results as number[]), maximum: rule.maximum, kind: "draft-primary-score" };
}

export function getExtendedAnswerGuidance(modelId: string, number: number) {
  if (modelId !== "oge-physics" || number < 17 || number > 22) return null;
  const experiment = number === 17, qualitative = number === 18 || number === 19;
  return {
    mode: "self-or-expert-only" as const,
    documentYear: 2026,
    status: "official-2026-fallback-not-certified-for-2027" as const,
    maximum: qualitative ? 2 : 3,
    source: { url: "https://doc.fipi.ru/oge/dlya-predmetnyh-komissiy-subektov-rf/2026/mr_oge_fizika_2026.pdf", pdfPages: experiment ? [11, 12, 13] : qualitative ? [14, 15, 16] : [17, 18, 19] },
    requiredElements: experiment ? ["Ресурс и схема реальной установки", "Результаты измерений с погрешностями", "Расчёт или вывод по конкретному типу эксперимента"] : qualitative ? ["Ответ на вопрос", "Физически корректное и достаточное обоснование"] : ["Краткое условие и перевод единиц", "Необходимые исходные законы и формулы", "Преобразования, расчёт и ответ с единицами"],
    limitations: ["Общая памятка, не готовая рубрика авторской задачи", "Частичные баллы зависят от типа и элементов конкретного ответа", "Эксперимент нельзя заменить текстом; автоматическая экспертная оценка запрещена", "Нужна отдельная сверка с критериями проекта 2027"],
  };
}
